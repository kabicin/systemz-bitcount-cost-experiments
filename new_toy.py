#!/usr/bin/env python3
"""Create a toy folder for one bit-count intrinsic and type.

    ./new_toy.py i128 ctlz            -> i128-ctlz/
    ./new_toy.py i64 cttz ctpop       -> i64-cttz/, i64-ctpop/
    ./new_toy.py v8i32 ctlz cttz      -> v8i32-ctlz/, v8i32-cttz/   (vector <8 x i32>)

Types: i8 i16 i32 i64 i128 (scalar) or vNiW (fixed vector, W = 8..64).
Each folder gets kernels.ll with three functions, measured by
../bitcount_toy.py, and a run.sh:
  @intrinsic  the intrinsic on its own
  @split      an alternative way to compute the same result:
                scalar (i16 and wider): two half-width intrinsics
                vector: one scalar intrinsic per lane
  @loop       d[i] = op(s[i]) over an array of the type
Scalar types also get:
  @slp2/4/8   2, 4 or 8 values loaded from memory, bit-counted, stored back
              (for the SLP vectorizer; only sizes up to 256 bits in total)
  @mix        d[i] = ext(op(s[i])) + e[i] mixing two widths, so the loop
              vectorizer has to choose a vectorization factor (below i128)
"""
import os
import re
import stat
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OPS = ("ctlz", "cttz", "ctpop")


def parse_type(name):
    m = re.match(r"^(?:v(\d+))?i(\d+)$", name)
    if not m:
        sys.exit("bad type %r: use iW (e.g. i64) or vNiW (e.g. v8i32)" % name)
    lanes, w = (int(m.group(1)) if m.group(1) else None), int(m.group(2))
    if lanes is None and w not in (8, 16, 32, 64, 128):
        sys.exit("scalar type must be i8, i16, i32, i64 or i128")
    if lanes is not None and (w not in (8, 16, 32, 64) or lanes < 2):
        sys.exit("vector element must be i8..i64 with at least 2 lanes")
    return lanes, w


def ir_type(lanes, w):
    return "i%d" % w if lanes is None else "<%d x i%d>" % (lanes, w)


def call(op, ty, val, zero_poison=False):
    extra = "" if op == "ctpop" else ", i1 %s" % ("true" if zero_poison else "false")
    return "call %s @llvm.%s.%s(%s %s%s)" % (ty, op, mangle(ty), ty, val, extra)


def mangle(ty):
    m = re.match(r"<(\d+) x (i\d+)>", ty)
    return "v%s%s" % (m.group(1), m.group(2)) if m else ty


def split_scalar(op, w):
    h = w // 2
    T, H = "i%d" % w, "i%d" % h
    lines = ["  %%lo = trunc %s %%x to %s" % (T, H),
             "  %%sh = lshr %s %%x, %d" % (T, h),
             "  %%hi = trunc %s %%sh to %s" % (T, H)]
    if op == "ctpop":
        lines += ["  %%a = %s" % call(op, H, "%lo"), "  %%b = %s" % call(op, H, "%hi"),
                  "  %%r.h = add %s %%a, %%b" % H]
        why = "ctpop(lo) + ctpop(hi)"
    else:
        # cttz looks at the low half first, ctlz at the high half first.
        first, second = ("%lo", "%hi") if op == "cttz" else ("%hi", "%lo")
        lines += ["  %%t1 = %s" % call(op, H, first, True),
                  "  %%t2 = %s" % call(op, H, second),
                  "  %%t2.h = add %s %%t2, %d" % (H, h),
                  "  %%nz = icmp ne %s %s, 0" % (H, first),
                  "  %%r.h = select i1 %%nz, %s %%t1, %s %%t2.h" % (H, H)]
        why = "%s != 0 ? %s(%s) : %d + %s(%s)" % (first[1:], op, first[1:], h, op, second[1:])
    lines += ["  %%r = zext %s %%r.h to %s" % (H, T), "  ret %s %%r" % T]
    return "two half-width operations: " + why, "\n".join(lines) + "\n"


def split_vector(op, lanes, w):
    T, S = ir_type(lanes, w), "i%d" % w
    lines, prev = [], "poison"
    for k in range(lanes):
        lines += ["  %%e%d = extractelement %s %%x, i32 %d" % (k, T, k),
                  "  %%c%d = %s" % (k, call(op, S, "%%e%d" % k)),
                  "  %%v%d = insertelement %s %s, %s %%c%d, i32 %d" % (k, T, prev, S, k, k)]
        prev = "%%v%d" % k
    lines.append("  ret %s %s" % (T, prev))
    return "one scalar %s per lane" % op, "\n".join(lines) + "\n"


def kernels(op, lanes, w):
    T = ir_type(lanes, w)
    nbytes = (lanes or 1) * w // 8
    align = min(16, max(1, nbytes))
    out = ["; %s on %s, generated by new_toy.py\n" % (op, T),
           "\n; The intrinsic on its own.\n",
           "define %s @intrinsic(%s %%x) {\n  %%r = %s\n  ret %s %%r\n}\n" % (T, T, call(op, T, "%x"), T)]
    alt = split_vector(op, lanes, w) if lanes else (split_scalar(op, w) if w >= 16 else None)
    if alt:
        why, body = alt
        out += ["\n; Alternative: %s.\n" % why, "define %s @split(%s %%x) {\n%s}\n" % (T, T, body)]
    if lanes is None:
        for n in SLP_SIZES:
            if n * w <= 256:
                out.append(slp_group(op, w, n))
        if w < 128:
            out.append(mix_loop(op, w))
    out += ["\n; d[i] = %s(s[i])\n" % op,
            "define void @loop(ptr noalias %d, ptr noalias %s, i64 %n) {\n",
            "entry:\n  br label %loop\nloop:\n",
            "  %i = phi i64 [ 0, %entry ], [ %i.next, %loop ]\n",
            "  %%ps = getelementptr inbounds %s, ptr %%s, i64 %%i\n" % T,
            "  %%x = load %s, ptr %%ps, align %d\n" % (T, align),
            "  %%c = %s\n" % call(op, T, "%x"),
            "  %%pd = getelementptr inbounds %s, ptr %%d, i64 %%i\n" % T,
            "  store %s %%c, ptr %%pd, align %d\n" % (T, align),
            "  %i.next = add nuw nsw i64 %i, 1\n",
            "  %done = icmp eq i64 %i.next, %n\n",
            "  br i1 %done, label %exit, label %loop\n",
            "exit:\n  ret void\n}\n"]
    return "".join(out)


SLP_SIZES = (2, 4, 8)


def slp_group(op, w, n):
    """n independent values loaded from consecutive memory, bit-counted and
    stored back: the shape the SLP vectorizer looks for."""
    T, a = "i%d" % w, w // 8
    lines = ["\n; d[0..%d] = %s(a[0..%d]): %d values from memory, for the SLP vectorizer.\n" % (n - 1, op, n - 1, n),
             "define void @slp%d(ptr noalias %%d, ptr noalias %%a) {\n" % n]
    for k in range(n):
        lines.append("  %%pa%d = getelementptr inbounds %s, ptr %%a, i64 %d\n" % (k, T, k))
        lines.append("  %%x%d = load %s, ptr %%pa%d, align %d\n" % (k, T, k, a))
    for k in range(n):
        lines.append("  %%c%d = %s\n" % (k, call(op, T, "%%x%d" % k)))
    for k in range(n):
        lines.append("  %%pd%d = getelementptr inbounds %s, ptr %%d, i64 %d\n" % (k, T, k))
        lines.append("  store %s %%c%d, ptr %%pd%d, align %d\n" % (T, k, k, a))
    lines.append("  ret void\n}\n")
    return "".join(lines)


def mix_loop(op, w):
    """A loop mixing two widths, so the loop vectorizer has to pick a
    vectorization factor from the costs: d[i] = ext(op(s[i])) + e[i]."""
    ow = 64 if w < 64 else 32
    T, O = "i%d" % w, "i%d" % ow
    conv = "zext" if ow > w else "trunc"
    return ("\n; d[i] = %s(%s(s[i])) + e[i], with s of %s and d, e of %s: the loop\n"
            "; vectorizer must choose a vectorization factor for two element widths.\n"
            "define void @mix(ptr noalias %%d, ptr noalias %%s, ptr noalias %%e, i64 %%n) {\n"
            "entry:\n  br label %%loop\nloop:\n"
            "  %%i = phi i64 [ 0, %%entry ], [ %%i.next, %%loop ]\n"
            "  %%ps = getelementptr inbounds %s, ptr %%s, i64 %%i\n"
            "  %%x = load %s, ptr %%ps, align %d\n"
            "  %%c = %s\n"
            "  %%cx = %s %s %%c to %s\n"
            "  %%pe = getelementptr inbounds %s, ptr %%e, i64 %%i\n"
            "  %%y = load %s, ptr %%pe, align %d\n"
            "  %%r = add %s %%cx, %%y\n"
            "  %%pd = getelementptr inbounds %s, ptr %%d, i64 %%i\n"
            "  store %s %%r, ptr %%pd, align %d\n"
            "  %%i.next = add nuw nsw i64 %%i, 1\n"
            "  %%done = icmp eq i64 %%i.next, %%n\n"
            "  br i1 %%done, label %%exit, label %%loop\n"
            "exit:\n  ret void\n}\n"
            % (conv, op, T, O, T, T, w // 8, call(op, T, "%x"), conv, T, O, O, O, ow // 8, O, O, O, ow // 8))


RUN_SH = """#!/usr/bin/env bash
# Measure this toy. Options are passed through, e.g. ./run.sh --cpus z13,z17
exec python3 "$(dirname "$0")/../bitcount_toy.py" "$(dirname "$0")" "$@"
"""


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    lanes, w = parse_type(sys.argv[1])
    for op in sys.argv[2:]:
        if op not in OPS:
            sys.exit("op must be one of " + ", ".join(OPS))
        d = os.path.join(HERE, "%s-%s" % (sys.argv[1], op))
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "kernels.ll"), "w") as f:
            f.write(kernels(op, lanes, w))
        p = os.path.join(d, "run.sh")
        with open(p, "w") as f:
            f.write(RUN_SH)
        os.chmod(p, os.stat(p).st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        print("created", os.path.relpath(d))


if __name__ == "__main__":
    main()
